import { test, expect } from "@playwright/test";
import { seed, reset, assertLocalRequests } from "./helpers";

test("filters, all analytics views, drilldowns and filtered CSV/JSON downloads", async ({ page, request }) => {
  await seed(request); assertLocalRequests(page);
  await page.goto("/statistics");
  await expect(page.getByText("3 of 3 payslips included", { exact: false })).toBeVisible();
  await expect(page.getByRole("status").filter({ hasText: "2 of 3 payslips with both figures have net pay greater than gross" })).toBeVisible();
  await page.getByRole("button", { name: "Review unexplained payslips" }).click();
  await expect(page.getByRole("dialog").getByRole("link")).toHaveCount(2);
  await page.getByRole("button", { name: "Close payslip list" }).click();
  await expect(page.getByRole("button", { name: "Gross - net difference", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Gross, net and deductions" })).toBeVisible();
  await page.getByRole("button", { name: /Gross pay.*observed values/ }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await expect(page.getByRole("dialog").getByRole("link")).toHaveCount(3);
  await page.getByRole("button", { name: "Close payslip list" }).click();
  const allocation = page.locator("section").filter({ has: page.getByRole("heading", { name: "Where gross goes", exact: true }) });
  const segment = allocation.locator('circle[role="button"]').first();
  const bounds = await segment.boundingBox();
  expect(bounds).not.toBeNull();
  await segment.click({ position: { x: bounds!.width - 3, y: bounds!.height / 2 } });
  await expect(page.getByRole("dialog").getByRole("link")).toHaveCount(1);
  await page.getByRole("button", { name: "Close payslip list" }).click();
  await page.getByRole("combobox", { name: "Employer", exact: true }).selectOption("Fixture Ltd");
  await expect(page.getByText("2 of 3 payslips included", { exact: false })).toBeVisible();
  for (const tab of ["Pay & deductions", "Hours & earnings", "Patterns", "Periods", "Data quality"]) {
    await page.getByRole("tab", { name: tab, exact: true }).click();
    await expect(page.getByRole("tabpanel")).toBeVisible();
    expect(await page.locator("body").innerText()).not.toContain("\\u00b7");
  }
  await page.getByRole("tab", { name: "Hours & earnings", exact: true }).click();
  for (const title of ["Overtime", "Bonus pay", "Holiday pay"]) await expect(page.getByRole("heading", { name: title, exact: true })).toBeVisible();
  await page.getByRole("tab", { name: "Pay & deductions", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Tax code (observed only)" })).toBeVisible();
  await page.getByRole("tab", { name: "Overview", exact: true }).click();
  const jsonDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export JSON" }).click();
  const json = await jsonDownload;
  const stream = await json.createReadStream();
  const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const report = JSON.parse(Buffer.concat(chunks).toString());
  expect(report.filter.employer).toBe("Fixture Ltd"); expect(report.statistics.count).toBe(2);
  expect(report.statistics.metrics.grossPay.total).toBe(5000);
  const csvDownload = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export CSV" }).click();
  expect((await csvDownload).suggestedFilename()).toBe("payslip-statistics.csv");
  await page.getByRole("combobox", { name: "Period", exact: true }).selectOption("custom");
  await page.getByLabel("From", { exact: true }).fill("2030-01-01");
  await page.getByLabel("To", { exact: true }).fill("2030-12-31");
  await expect(page.getByRole("heading", { name: "No payslips match these filters." })).toBeVisible();
  await page.getByRole("button", { name: "Reset filters", exact: true }).first().click();
  await expect(page.getByText("3 of 3 payslips included", { exact: false })).toBeVisible();
  await page.screenshot({ path: "test-results/statistics-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "test-results/statistics-mobile.png", fullPage: true });
  await reset(request);
});
